export function normalizeEmail(value: unknown): string {
  return typeof value === "string" ? value.trim().toLowerCase() : "";
}

export function emailDomain(email: string): string {
  const at = email.lastIndexOf("@");
  return at > 0 ? email.slice(at + 1).toLowerCase() : "";
}

/** True for known temporary/disposable providers (incl. their subdomains). */
export function isDisposableEmail(value: unknown): boolean {
  const domain = emailDomain(normalizeEmail(value));
  if (!domain || !domain.includes(".")) return false;
  if (DISPOSABLE_DOMAINS.has(domain)) return true;
  for (const d of DISPOSABLE_DOMAINS) {
    if (domain.endsWith(`.${d}`)) return true;
  }
  return false;
}

